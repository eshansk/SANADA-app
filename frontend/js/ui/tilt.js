/**
 * frontend/js/ui/tilt.js
 * ======================
 * 3D Hover & Mobile Touch Tilt & Light Bevel Reflection Coordinator.
 * Gives cards a subtle, luxurious 3D perspective hover/tap tilt and dynamically
 * sweeps the specular light bevel along the edge matching the tilt angle.
 * Supports both mouse hover and mobile tap/touch gestures, ensuring cards
 * always smoothly return to their flat resting position when a tap completes.
 */

export function initCardTilt() {
    if (typeof window === 'undefined') return;

    const cardSelector = '.card, .stat-tile, .home-task-card, .ceiling-explorer-card, .pipeline-step-card, .auth-card';
    let currentCard = null;
    let rafId = null;
    let touchResetTimer = null;
    let isTouchActive = false;
    let lastTouchTime = 0;

    function applyTilt(card, clientX, clientY) {
        const rect = card.getBoundingClientRect();
        if (!rect.width || !rect.height) return;

        // Normalized coordinates across the card (0.0 to 1.0)
        const px = Math.max(0, Math.min(1, (clientX - rect.left) / rect.width));
        const py = Math.max(0, Math.min(1, (clientY - rect.top) / rect.height));

        // Ultra-refined 3D tilt: ±3.0 degrees max to avoid visual distortion
        const rotX = ((0.5 - py) * 6.0).toFixed(2);
        const rotY = ((px - 0.5) * 6.0).toFixed(2);

        // Dynamically sweep the light bevel along the edge matching the tilt angle
        const bevelShift = (35 + px * 260).toFixed(1);
        const counterShift = (-35 - (1 - px) * 260).toFixed(1);

        card.style.setProperty('--card-rot-x', `${rotX}deg`);
        card.style.setProperty('--card-rot-y', `${rotY}deg`);
        card.style.setProperty('--card-bevel-x', `${bevelShift}%`);
        card.style.setProperty('--card-counter-bevel-x', `${counterShift}%`);
    }

    function resetCard(card, immediate = false) {
        if (!card) return;
        card.classList.remove('is-tapped');
        if (immediate) {
            card.style.removeProperty('--card-rot-x');
            card.style.removeProperty('--card-rot-y');
            card.style.removeProperty('--card-bevel-x');
            card.style.removeProperty('--card-counter-bevel-x');
            card.style.transform = '';
        } else {
            // Allow CSS transition to gracefully ease back to resting state
            // before stripping inline custom properties (synced to 0.45s return transition)
            setTimeout(() => {
                if (!card.classList.contains('is-tapped')) {
                    card.style.removeProperty('--card-rot-x');
                    card.style.removeProperty('--card-rot-y');
                    card.style.removeProperty('--card-bevel-x');
                    card.style.removeProperty('--card-counter-bevel-x');
                    card.style.transform = '';
                }
            }, 450);
        }
    }

    function resetAllCards(immediate = false) {
        if (rafId) {
            cancelAnimationFrame(rafId);
            rafId = null;
        }
        document.querySelectorAll(cardSelector).forEach(c => {
            if (c.classList.contains('is-tapped') || c.style.getPropertyValue('--card-rot-x')) {
                resetCard(c, immediate);
            }
        });
        currentCard = null;
    }

    // --- MOUSE HOVER HANDLERS ---
    function handleMouseMove(e) {
        // Discard emulated or synthetic mouse events generated by touchscreens
        if (isTouchActive || (Date.now() - lastTouchTime < 1000)) return;
        if (e.sourceCapabilities && e.sourceCapabilities.firesTouchEvents) return;

        const card = e.target.closest(cardSelector);
        if (!card) {
            if (currentCard) {
                resetCard(currentCard, false);
                currentCard = null;
            }
            return;
        }

        currentCard = card;

        // Skip intense tracking on interactive controls inside cards to preserve precision
        if (e.target.closest('input, button, select, textarea, audio, [role="button"], a')) {
            return;
        }

        if (rafId) cancelAnimationFrame(rafId);
        rafId = requestAnimationFrame(() => {
            applyTilt(card, e.clientX, e.clientY);
        });
    }

    function handleMouseOut(e) {
        if (isTouchActive || (Date.now() - lastTouchTime < 1000)) return;
        const card = e.target.closest(cardSelector);
        if (card && (!e.relatedTarget || !card.contains(e.relatedTarget))) {
            resetCard(card, false);
            if (currentCard === card) currentCard = null;
        }
    }

    // --- MOBILE TOUCH / TAP HANDLERS ---
    function handleTouchStart(e) {
        if (!e.touches || !e.touches[0]) return;
        isTouchActive = true;
        lastTouchTime = Date.now();

        if (touchResetTimer) {
            clearTimeout(touchResetTimer);
            touchResetTimer = null;
        }

        const touch = e.touches[0];
        const card = e.target.closest(cardSelector);
        if (!card) {
            resetAllCards(false);
            return;
        }

        // Reset any previously tapped card immediately so the newly tapped card activates
        if (currentCard && currentCard !== card) {
            resetCard(currentCard, true);
        }

        currentCard = card;
        card.classList.add('is-tapped');
        applyTilt(card, touch.clientX, touch.clientY);
    }

    function handleTouchMove(e) {
        lastTouchTime = Date.now();
        if (!e.touches || !e.touches[0]) return;
        const touch = e.touches[0];

        // Track and activate whichever card is currently under the moving finger while scrolling
        const targetElement = document.elementFromPoint(touch.clientX, touch.clientY);
        const card = (targetElement && targetElement.closest) ? (targetElement.closest(cardSelector) || currentCard) : currentCard;

        if (card) {
            if (currentCard && currentCard !== card) {
                resetCard(currentCard, false);
            }
            currentCard = card;
            card.classList.add('is-tapped');

            if (rafId) cancelAnimationFrame(rafId);
            rafId = requestAnimationFrame(() => {
                applyTilt(card, touch.clientX, touch.clientY);
            });
        }
    }

    function handleTouchEnd() {
        isTouchActive = false;
        lastTouchTime = Date.now();
        if (rafId) {
            cancelAnimationFrame(rafId);
            rafId = null;
        }

        if (touchResetTimer) {
            clearTimeout(touchResetTimer);
            touchResetTimer = null;
        }

        // Zero touch release hold delay: immediately begin easing back to flat resting position over 0.45s
        resetAllCards(false);
    }

    function handleTouchCancel() {
        isTouchActive = false;
        lastTouchTime = Date.now();
        if (touchResetTimer) {
            clearTimeout(touchResetTimer);
            touchResetTimer = null;
        }
        resetAllCards(false);
    }

    // Attach passive listeners on document for zero jank & dynamic DOM compatibility
    document.addEventListener('mousemove', handleMouseMove, { passive: true });
    document.addEventListener('mouseout', handleMouseOut, { passive: true });
    document.addEventListener('touchstart', handleTouchStart, { passive: true });
    document.addEventListener('touchmove', handleTouchMove, { passive: true });
    document.addEventListener('touchend', handleTouchEnd, { passive: true });
    document.addEventListener('touchcancel', handleTouchCancel, { passive: true });
}
